function bindShelfDrag11(shelf) {
  let start = null;
  let dragged = false;
  shelf.onpointerdown = event => {
    if (!event.isPrimary || event.button !== 0 || entering9) return;
    dragged = false;
    start = { x: event.clientX, y: event.clientY, id: event.pointerId };
  };
  shelf.onpointermove = event => {
    if (start?.id !== event.pointerId) return;
    const dx = event.clientX - start.x;
    if (!dragged && Math.abs(dx) > 9 && Math.abs(dx) > Math.abs(event.clientY - start.y)) {
      dragged = true;
      shelf.setPointerCapture(event.pointerId);
      shelf.classList.add('dragging11');
    }
    if (dragged) shelf.style.setProperty('--drag11', Math.max(-180, Math.min(180, dx)) + 'px');
  };
  const finish = event => {
    if (start?.id !== event.pointerId) return;
    const dx = event.clientX - start.x;
    start = null;
    shelf.classList.remove('dragging11');
    shelf.style.removeProperty('--drag11');
    if (dragged && event.type === 'pointerup' && Math.abs(dx) > 36) moveShelf7(-Math.sign(dx));
  };
  shelf.onpointerup = shelf.onpointercancel = shelf.onlostpointercapture = finish;
  shelf.onpointerleave = () => { if (!dragged) start = null; };
  shelf.addEventListener('click', event => {
    if (!dragged || event.detail === 0) return;
    dragged = false;
    event.preventDefault();
    event.stopImmediatePropagation();
  }, true);
  shelf.ondragstart = event => event.preventDefault();
}

